#!/bin/sh
# ОСТАНОВКА службы matrix-hs — парная к scripts/stand-lift.sh.
#
# Скрипт вынесен из soak-каталога стенда в репозиторий: инцидент окна измерений
# показал, что гейт остановки объявлял провал там, где служба уже остановлена.
# Прежняя проверка ждала только освобождения ПОРТА и ничего не говорила о том,
# умер ли процесс; при мёртвом pid в pid-файле и свободном порте прогон
# доходил до таймаута и возвращал «порт не освободился» — то есть отвечал
# «остановить не удалось» на состояние «остановлено». Ниже порядок
# выверку: сначала СМЕРТЬ процесса, и только потом — порт.
#
# Ничего host-local здесь не зашито, ровно как в stand-lift: путь к дому
# стенда приходит в STAND_HOME, порт выводится из MATRIX_HS_LISTEN в его env.
# Иначе check_no_private справедливо отказывает — путь под /home или номер
# порта в публикуемом файле это карта развёртывания, и проверка «тот ли это
# порт» на чужом стенде врала бы.
#
# ЗАПУСКАТЬ ПОД ПОЛЬЗОВАТЕЛЕМ службы, не под root:
#   STAND_HOME=<дом стенда> sh window7-stop-service.sh
#
# КОДЫ ВЫХОДА (значение важно автоматике, не только человеку):
#   0 — служба остановлена: процесс мёртв И порт свободен; pid-файл удалён
#   2 — pid-файл отсутствует, пуст, нечисловой или неположителен
#   3 — pid занят ЧУЖИМ процессом: kill не отправлен, ничего не тронуто
#   4 — порт занят после подтверждённой смерти процесса (или при протухшем
#       pid): служба мертва, но порт держит кто-то другой
#   5 — kill -TERM не удался отправить
#   6 — процесс пережил TERM за отведённое время; -9 НЕ шлём никогда
#
# ПОЧЕМУ НИКОГДА НЕ -9: -TERM оставляет аллокатору дописать статистику
# (stats_print) перед выходом, и без неё финальный снимок окна не появится.
# Поэтому вместо эскалации сигнала код 6 и ожидание следующего окна.
#
# ИНСТРУМЕНТ НА ЭТОЙ НОДЕ: `sockstat -L` в FreeBSD НЕ СУЩЕСТВУЕТ (в usage
# флага -L нет), поэтому порт меряется `sockstat -4 -l -p <порт>`. Совпадение
# ищем по ':<порт>' в адресе, а НЕ `grep -q .`: sockstat печатает заголовок
# таблицы, и `grep -q .` считает занятым свободный порт.
set -eu

: "${STAND_HOME:?STAND_HOME не задан — укажи дом стенда (каталог с mrgd.env)}"
case "$STAND_HOME" in
	/*) : ;;
	*)  echo "stop-service: STAND_HOME='$STAND_HOME' — нужен абсолютный путь." >&2; exit 2 ;;
esac

ENV_FILE=${STOP_ENV:-$STAND_HOME/mrgd.env}
LOG=${STOP_LOG:-$STAND_HOME/soak/stand-service.log}
PIDFILE=${STOP_PIDFILE:-$STAND_HOME/mrgd.pid}
# Строгая проверка «это НАША сборка»: pid-файл общий для окон, и без неё
# остановка одного окна убила бы живой стенд другого. Переопределяется, если
# очередной сборке дано другое имя.
EXPECT_CMD=${STOP_EXPECT_CMD:-matrix-hs.window7}
DEATH_TIMEOUT=${STOP_DEATH_TIMEOUT:-30}
PORT_TIMEOUT=${STOP_PORT_TIMEOUT:-30}

case "$DEATH_TIMEOUT:$PORT_TIMEOUT" in
	*[!0-9:]* | :* | *:) echo "stop-service: таймауты не числа: '$DEATH_TIMEOUT'/'$PORT_TIMEOUT'" >&2; exit 2 ;;
esac

mkdir -p "$(dirname "$LOG")" 2>/dev/null || :

# Строка в журнал службы пишется ОДИН раз на прогон, и код в ней зеркалит
# выходной код — иначе разбор инцидента читает rc=0 в логе при ненулевом коде
# в терминале (именно так выглядел инцидент: rc=1 в строке лога, rc=4 наружу).
PID=none
finish() {
	printf '[launcher] window7 stop epoch=%s pid=%s rc=%s\n' \
		"$(date -u +%s)" "$PID" "$1" >> "$LOG" 2>/dev/null || :
	exit "$1"
}

alive() { kill -0 "$1" 2>/dev/null; }

# Порт берём из того же env, что и подъём: несовпадение порта с пид-файлом
# означало бы, что мы мерим чужой сокет. STOP_PORT — явный перебор env.
PORT=${STOP_PORT:-}
if [ -z "$PORT" ] && [ -r "$ENV_FILE" ]; then
	_listen=$(sed -n 's/^MATRIX_HS_LISTEN=//p' "$ENV_FILE" | tail -1)
	case "${_listen:-}" in
	'' | *:*) : ;;
	*)
		echo "stop-service: в env не читается MATRIX_HS_LISTEN='${_listen}'" >&2
		finish 2
		;;
	esac
	[ -n "${_listen:-}" ] && PORT=${_listen##*:}
fi
case "$PORT" in
'' | *[!0-9]*)
	echo "stop-service: не знаю порт (задай STOP_PORT или MATRIX_HS_LISTEN в env): '$PORT'" >&2
	finish 2
	;;
esac

# ── Гейт 1: pid-файл ────────────────────────────────────────────────────────
if [ ! -s "$PIDFILE" ]; then
	echo "stop-service: pid-файл отсутствует или пуст: $PIDFILE" >&2
	exit 2
fi
PID=$(tr -d '[:space:]' < "$PIDFILE")
case "$PID" in
'' | *[!0-9]*)
	echo "stop-service: pid не числовой: '$PID'" >&2
	exit 2
	;;
esac
if [ "$PID" -le 0 ]; then
	echo "stop-service: pid не положителен: $PID" >&2
	exit 2
fi

# ── Гейт 2: это вообще наша служба? ──────────────────────────────────────────
# Читаем имя процесса ДО kill: после смерти pid-файл уже не даст его прочитать.
CMD=$(ps -p "$PID" -o command= 2>/dev/null || true)

if alive "$PID"; then
	if ! printf '%s\n' "$CMD" | grep -q 'matrix-hs'; then
		echo "stop-service: pid $PID не matrix-hs ('$CMD') — НЕ КИЛЛЮ" >&2
		exit 3
	fi
	case "$CMD" in
	*"$EXPECT_CMD"*) : ;;
	*)
		echo "stop-service: pid $PID = '$CMD', это не $EXPECT_CMD (живой стенд другого окна?) — НЕ КИЛЛЮ" >&2
		exit 3
		;;
	esac

	# ── TERM ────────────────────────────────────────────────────────────────
	if ! kill -TERM "$PID"; then
		echo "stop-service: kill -TERM $PID не удался" >&2
		finish 5
	fi

	# ── Гейт 3: ЖДЁМ СМЕРТИ процесса, и только потом смотрим на порт ─────────
	# Прежний порядок ждал только порт и умел объявить «остановить не удалось»
	# уже мёртвому процессу. kill -0 на мёртвом pid не срабатывает — это и есть
	# признак смерти, который нам нужен.
	_i=0
	while alive "$PID" && [ "$_i" -lt "$DEATH_TIMEOUT" ]; do
		_i=$(( _i + 1 ))
		sleep 1
	done
	if alive "$PID"; then
		echo "stop-service: pid $PID пережил TERM за ${DEATH_TIMEOUT}s — -9 НЕ шлю." >&2
		finish 6
	fi
else
	# ── Протухший pid-файл: процесса нет, убивать нечего ─────────────────────
	# Это НЕ ошибка. Прежний гейт отвечал здесь «процесса нет — НЕ КИЛЛЮ» (rc=3),
	# а когда порт при этом успевал освободиться — не доходил до проверки вовсе
	# и в других сборках гейта выдавал rc=4 на состояние «уже остановлено».
	# Проверка порта ниже даёт этому состоянию честный rc=0.
	echo "stop-service: pid $PID уже мёртв — TERM не шлю, проверяю порт $PORT."
fi

# ── Гейт 4: порт свободен? Теперь это осмысленно: процесс мёртв ─────────────
_i=0
while [ "$_i" -lt "$PORT_TIMEOUT" ]; do
	if ! sockstat -4 -l -p "$PORT" 2>/dev/null | grep -q ":$PORT"; then
		break
	fi
	_i=$(( _i + 1 ))
	sleep 1
done
if sockstat -4 -l -p "$PORT" 2>/dev/null | grep -q ":$PORT"; then
	echo "stop-service: процесс мёртв, но порт $PORT держит кто-то другой:" >&2
	sockstat -4 -l -p "$PORT" >&2 2>/dev/null || :
	finish 4
fi

# ── Гейт 5: pid-файл принадлежит остановленной службе — убираем ──────────────
# Иначе следующий подъём прочитает в нём мёртвый pid и объявит, что служба уже
# работает, а мерить будет нечего. Удаляем только сейчас: после подтверждённой
# смерти и свободного порта pid-файл — единственное, что осталось от службы.
if [ -f "$PIDFILE" ]; then
	_now=$(tr -d '[:space:]' < "$PIDFILE" 2>/dev/null || true)
	if [ "$_now" = "$PID" ]; then
		rm -f "$PIDFILE"
		echo "stop-service: ОСТАНОВЛЕН (pid=$PID, порт $PORT свободен), pid-файл удалён."
	else
		echo "stop-service: pid-файл уже принадлежит другому pid ($_now) — не трогаю."
	fi
fi

finish 0